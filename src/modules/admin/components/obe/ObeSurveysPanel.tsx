// src/modules/admin/components/obe/ObeSurveysPanel.tsx
// Staff side of the indirect-assessment slice: open a course-exit round for a
// published mapping, watch how many answers have come in, and read the folded
// per-CO means that a run will use.
//
// Deliberately small. The numbers shown here come from the `previewObeSurveyScores`
// callable — the same fold the run performs — so there is exactly one answer to
// "what will the 20% be", and the panel cannot drift from the engine.
//
// Alumni and employer feedback is collected outside the portal (older batches
// have no portal accounts), so those two audiences are NOT offered as rounds
// here; they go into a run through the paste box, whose CSV is generated by
// `surveyAggregateCsv` from a round of either kind.

import { useMemo, useState } from 'react';
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { AlertTriangle, ClipboardCheck, ClipboardList, Copy, Loader2, Lock, Unlock } from 'lucide-react';
import type { ObeMappingDoc } from '@/shared/types/obe';
import {
  OBE_SURVEY_AUDIENCES,
  STUDENT_ANSWERABLE_AUDIENCES,
  type ObeSurveyAudience,
  type ObeSurveyDoc,
} from '@/shared/types/obeSurvey';
import { normalizeSurveyScale, surveyAggregateCsv } from '@/shared/utils/obeSurvey';
import {
  fetchObeSurveyAggregate,
  fetchObeSurveysForMapping,
  openObeSurvey,
  setObeSurveyStatus,
} from '../../api/obeSurveyApi';

const CARD = 'rounded-xl border border-slate-200 bg-white p-4 dark:border-slate-700 dark:bg-slate-900';

function audienceLabel(survey: ObeSurveyDoc): string {
  return OBE_SURVEY_AUDIENCES.find((a) => a.id === survey.audience)?.label ?? survey.audience;
}

function RoundRow({ survey, canManage }: { survey: ObeSurveyDoc; canManage: boolean }) {
  const queryClient = useQueryClient();
  const [expanded, setExpanded] = useState(false);
  const [copied, setCopied] = useState(false);
  const open = survey.status === 'open';

  const aggregateQuery = useQuery({
    queryKey: ['obeSurveyAggregate', survey.id, expanded],
    enabled: expanded,
    queryFn: () => fetchObeSurveyAggregate(survey.id),
  });

  const statusMutation = useMutation({
    mutationFn: (status: 'open' | 'closed') => setObeSurveyStatus(survey.id, status),
    onSuccess: () => {
      void queryClient.invalidateQueries({ queryKey: ['obeSurveys', survey.mappingId] });
    },
  });

  async function copyCsv() {
    const aggregate = aggregateQuery.data;
    if (!aggregate) return;
    try {
      await navigator.clipboard.writeText(surveyAggregateCsv(aggregate));
      setCopied(true);
      window.setTimeout(() => setCopied(false), 2000);
    } catch {
      setCopied(false);
    }
  }

  return (
    <div className="border-b border-slate-100 py-3 last:border-b-0 dark:border-slate-800">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <div className="min-w-0">
          <p className="flex flex-wrap items-center gap-2 text-sm font-bold text-slate-800 dark:text-slate-100">
            {audienceLabel(survey)}
            <span
              className={`rounded-full px-2 py-0.5 text-[10px] font-bold uppercase tracking-wide ${
                open
                  ? 'bg-emerald-50 text-emerald-700 dark:bg-emerald-950/40 dark:text-emerald-300'
                  : 'bg-slate-100 text-slate-500 dark:bg-slate-800 dark:text-slate-400'
              }`}
            >
              {open ? 'Collecting' : 'Closed'}
            </span>
          </p>
          <p className="mt-0.5 text-xs text-slate-500 dark:text-slate-400">
            {survey.cos.length} outcomes · scale 1–{survey.scaleMax}
            {survey.academicYear ? ` · ${survey.academicYear}` : ''}
            {survey.term ? ` · ${survey.term}` : ''}
          </p>
        </div>
        <div className="flex items-center gap-2">
          <button
            type="button"
            onClick={() => setExpanded((value) => !value)}
            className="inline-flex items-center gap-1.5 rounded-lg border border-slate-300 px-2.5 py-1.5 text-xs font-bold text-slate-700 hover:bg-slate-50 dark:border-slate-600 dark:text-slate-200 dark:hover:bg-slate-800"
          >
            <ClipboardCheck size={14} /> {expanded ? 'Hide answers' : 'Answers so far'}
          </button>
          {canManage && (
            <button
              type="button"
              disabled={statusMutation.isPending}
              onClick={() => statusMutation.mutate(open ? 'closed' : 'open')}
              className={`inline-flex items-center gap-1.5 rounded-lg px-2.5 py-1.5 text-xs font-bold ${
                open
                  ? 'border border-slate-300 text-slate-700 hover:bg-slate-50 dark:border-slate-600 dark:text-slate-200'
                  : 'bg-teal-600 text-white hover:bg-teal-700'
              } disabled:opacity-50`}
            >
              {statusMutation.isPending ? (
                <Loader2 size={14} className="animate-spin" />
              ) : open ? (
                <Lock size={14} />
              ) : (
                <Unlock size={14} />
              )}
              {open ? 'Close round' : 'Reopen'}
            </button>
          )}
        </div>
      </div>

      {statusMutation.isError && (
        <p className="mt-2 text-xs font-semibold text-rose-600">
          Could not change the round status. Only staff of this college can, and the mapping must still be published.
        </p>
      )}

      {expanded && (
        <div className="mt-3 rounded-lg bg-slate-50 p-3 dark:bg-slate-800">
          {aggregateQuery.isLoading && (
            <p className="flex items-center gap-2 text-xs text-slate-500">
              <Loader2 size={13} className="animate-spin" /> Folding stored answers…
            </p>
          )}
          {aggregateQuery.isError && (
            <p className="text-xs font-semibold text-rose-600">Could not fold this round's answers.</p>
          )}
          {aggregateQuery.data && (
            <>
              <p className="text-xs font-semibold text-slate-600 dark:text-slate-300">
                {aggregateQuery.data.responseCount} answer{aggregateQuery.data.responseCount === 1 ? '' : 's'}
                {aggregateQuery.data.completeCount !== aggregateQuery.data.responseCount && (
                  <> · {aggregateQuery.data.completeCount} rated every outcome</>
                )}
                {aggregateQuery.data.responseCount < 5 && aggregateQuery.data.responseCount > 0 && (
                  <span className="ml-1 font-normal text-amber-700 dark:text-amber-300">
                    (fewer than 5 — treat as indicative, not representative)
                  </span>
                )}
              </p>
              {aggregateQuery.data.coSummaries.length === 0 ? (
                <p className="mt-2 text-xs text-slate-500">No ratings yet. Students see this round in their Feedback page.</p>
              ) : (
                <div className="mt-2 overflow-x-auto">
                  <table className="w-full text-left text-xs">
                    <thead className="text-[10px] uppercase tracking-wide text-slate-500">
                      <tr>
                        <th className="py-1 pr-3">Outcome</th>
                        <th className="py-1 pr-3">Mean</th>
                        <th className="py-1 pr-3">Ratings</th>
                        <th className="py-1">On the 0–3 scale</th>
                      </tr>
                    </thead>
                    <tbody className="font-semibold text-slate-700 dark:text-slate-200">
                      {aggregateQuery.data.coSummaries.map((summary) => (
                        <tr key={summary.co} className="border-t border-slate-200 dark:border-slate-700">
                          <td className="py-1 pr-3">{summary.co}</td>
                          <td className="py-1 pr-3 tabular-nums">
                            {summary.mean} / {summary.scaleMax}
                          </td>
                          <td className="py-1 pr-3 tabular-nums">{summary.count}</td>
                          <td className="py-1 tabular-nums">{summary.level}</td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              )}
              {aggregateQuery.data.coSummaries.length > 0 && (
                <button
                  type="button"
                  onClick={() => void copyCsv()}
                  className="mt-2 inline-flex items-center gap-1.5 text-xs font-bold text-teal-700 hover:underline dark:text-teal-300"
                >
                  <Copy size={13} /> {copied ? 'Copied — paste into a new run' : 'Copy as survey CSV (for a run)'}
                </button>
              )}
            </>
          )}
        </div>
      )}
    </div>
  );
}

export function ObeSurveysPanel({ mapping, canManage }: { mapping: ObeMappingDoc; canManage: boolean }) {
  const queryClient = useQueryClient();
  const [audience, setAudience] = useState<ObeSurveyAudience>('course-exit');
  const [scale, setScale] = useState('5');
  const [prompt, setPrompt] = useState('');
  const [error, setError] = useState<string | null>(null);

  const surveysQuery = useQuery({
    queryKey: ['obeSurveys', mapping.id],
    queryFn: () => fetchObeSurveysForMapping(mapping.id),
  });

  const openMutation = useMutation({
    mutationFn: () =>
      openObeSurvey({
        mappingId: mapping.id,
        audience,
        scaleMax: normalizeSurveyScale(scale),
        ...(prompt.trim() ? { prompt: prompt.trim() } : {}),
      }),
    onSuccess: () => {
      setPrompt('');
      setError(null);
      void queryClient.invalidateQueries({ queryKey: ['obeSurveys', mapping.id] });
    },
    onError: (err) => setError(err instanceof Error ? err.message : 'Could not open the round.'),
  });

  const studentFacing = useMemo(
    () => OBE_SURVEY_AUDIENCES.filter((a) => STUDENT_ANSWERABLE_AUDIENCES.includes(a.id)),
    [],
  );
  const selectedAudience = studentFacing.find((a) => a.id === audience) ?? studentFacing[0];
  const openRoundExists = (surveysQuery.data ?? []).some(
    (survey) => survey.status === 'open' && survey.audience === audience,
  );

  return (
    <section className={CARD}>
      <h2 className="flex items-center gap-2 text-sm font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400">
        <ClipboardList size={16} /> Indirect assessment (surveys)
      </h2>
      <p className="mt-1 text-xs text-slate-500 dark:text-slate-400">
        Students rate each course outcome in their portal; those ratings become the indirect share of the
        run. Alumni and employer feedback is still collected outside the portal — copy a round's CSV and
        paste it into a run instead of opening one here.
      </p>

      {surveysQuery.isLoading && (
        <p className="mt-3 flex items-center gap-2 text-xs text-slate-500">
          <Loader2 size={13} className="animate-spin" /> Loading rounds…
        </p>
      )}
      {surveysQuery.isError && (
        <p className="mt-3 text-xs font-semibold text-rose-600">Could not load this course's rounds.</p>
      )}

      {(surveysQuery.data ?? []).length > 0 && (
        <div className="mt-3">
          {(surveysQuery.data ?? []).map((survey) => (
            <RoundRow key={survey.id} survey={survey} canManage={canManage} />
          ))}
        </div>
      )}

      {!surveysQuery.isLoading && (surveysQuery.data ?? []).length === 0 && (
        <p className="mt-3 rounded-lg bg-slate-50 p-3 text-xs text-slate-500 dark:bg-slate-800 dark:text-slate-400">
          No round has been opened for {mapping.courseCode} yet. Open one below after the course's last
          assessment is graded, and tell students to check their Feedback page — the round stays open until
          you close it.
        </p>
      )}

      {canManage && (
        <div className="mt-4 rounded-lg border border-dashed border-slate-300 p-3 dark:border-slate-700">
          <div className="grid gap-3 sm:grid-cols-[minmax(0,2fr)_minmax(0,1fr)]">
            <label className="block">
              <span className="text-xs font-bold uppercase tracking-wide text-slate-500">Audience</span>
              <select
                value={audience}
                onChange={(e) => setAudience(e.target.value as ObeSurveyAudience)}
                className="mt-1 w-full rounded-lg border border-slate-200 bg-white px-3 py-2 text-sm dark:border-slate-700 dark:bg-slate-800"
              >
                {studentFacing.map((option) => (
                  <option key={option.id} value={option.id}>
                    {option.label}
                  </option>
                ))}
              </select>
              <span className="mt-1 block text-xs text-slate-500 dark:text-slate-400">
                {selectedAudience?.hint}
              </span>
            </label>
            <label className="block">
              <span className="text-xs font-bold uppercase tracking-wide text-slate-500">Scale top</span>
              <input
                value={scale}
                onChange={(e) => setScale(e.target.value)}
                inputMode="numeric"
                className="mt-1 w-full rounded-lg border border-slate-200 bg-white px-3 py-2 text-sm tabular-nums dark:border-slate-700 dark:bg-slate-800"
              />
              <span className="mt-1 block text-xs text-slate-500 dark:text-slate-400">1 to this number (2–10).</span>
            </label>
          </div>
          <label className="mt-3 block">
            <span className="text-xs font-bold uppercase tracking-wide text-slate-500">Line shown to students (optional)</span>
            <input
              value={prompt}
              onChange={(e) => setPrompt(e.target.value)}
              placeholder="e.g. Think about the assignments, labs and exams of this course."
              className="mt-1 w-full rounded-lg border border-slate-200 bg-white px-3 py-2 text-sm dark:border-slate-700 dark:bg-slate-800"
            />
          </label>
          {openRoundExists && (
            <p className="mt-2 flex items-center gap-1.5 text-xs font-semibold text-amber-700 dark:text-amber-300">
              <AlertTriangle size={13} /> A {selectedAudience?.label.toLowerCase()} round is already collecting —
              opening another will be refused. Close it first if you want a fresh one.
            </p>
          )}
          {error && <p className="mt-2 text-xs font-semibold text-rose-600">{error}</p>}
          <button
            type="button"
            disabled={openMutation.isPending || openRoundExists}
            onClick={() => openMutation.mutate()}
            className="mt-3 inline-flex items-center gap-2 rounded-lg bg-teal-600 px-3.5 py-2 text-sm font-bold text-white hover:bg-teal-700 disabled:cursor-not-allowed disabled:opacity-50"
          >
            {openMutation.isPending ? <Loader2 size={15} className="animate-spin" /> : <ClipboardList size={15} />}
            Open round
          </button>
        </div>
      )}

      {!canManage && (
        <p className="mt-3 text-xs text-slate-500 dark:text-slate-400">
          Only staff who can manage this mapping's college can open or close a round.
        </p>
      )}
    </section>
  );
}

export default ObeSurveysPanel;
